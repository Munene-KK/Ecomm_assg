import mongoose from "mongoose";
const Schema = mongoose.Schema;

const poductSchema = new Schema(
  {
    name: {
      type: String,
      required: true,
      trim: true,
    },
    price: {
      type: Number,
      required: true,
    },
    image: {
      type: String,
      required: true,
      trim: true,
    },
    description: {
      type: String,
      required: true,
      trim: true,
    },
    category: {
      type: String,
      required: true,
      trim: true,
    },
    status: {
      type: String,
      trim: true,
      default: "In stock",
    },
  },
  { timestamps: true },
);
export const Product = mongoose.model("Product", poductSchema);
